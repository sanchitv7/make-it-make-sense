#!/usr/bin/env node
/**
 * Copy Silero VAD worklet/ONNX and the onnxruntime WASM pair into public/vad/
 * so the browser can load them without a CDN.
 *
 * Only the standard threaded WASM is copied (not asyncify/jsep/jspi variants).
 */
import { cpSync, mkdirSync, existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dest = join(root, "public", "vad");
const vadDist = join(root, "node_modules", "@ricky0123", "vad-web", "dist");
const ortDist = join(root, "node_modules", "onnxruntime-web", "dist");

if (!existsSync(vadDist) || !existsSync(ortDist)) {
  console.warn("[copy-vad-assets] Dependencies not installed yet; skipping.");
  process.exit(0);
}

mkdirSync(dest, { recursive: true });

const copies = [
  [join(vadDist, "vad.worklet.bundle.min.js"), "vad.worklet.bundle.min.js"],
  [join(vadDist, "silero_vad_v5.onnx"), "silero_vad_v5.onnx"],
  [join(vadDist, "silero_vad_legacy.onnx"), "silero_vad_legacy.onnx"],
  [join(ortDist, "ort-wasm-simd-threaded.wasm"), "ort-wasm-simd-threaded.wasm"],
  [join(ortDist, "ort-wasm-simd-threaded.mjs"), "ort-wasm-simd-threaded.mjs"],
];

for (const [src, name] of copies) {
  if (!existsSync(src)) {
    console.warn(`[copy-vad-assets] Missing ${name}, skipping.`);
    continue;
  }
  cpSync(src, join(dest, name));
}

writeFileSync(
  join(dest, "README.md"),
  [
    "# Silero VAD assets",
    "",
    "Generated by `npm run copy-vad-assets` / `postinstall`.",
    "Do not edit by hand — re-run the script after upgrading `@ricky0123/vad-web` or `onnxruntime-web`.",
    "",
  ].join("\n"),
);

console.log(`[copy-vad-assets] Copied assets to ${dest}`);
